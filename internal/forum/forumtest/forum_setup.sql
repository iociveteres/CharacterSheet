-- The schema is the search_path of the connection (forumtest.NewDB): the name lives in one place.
DO $$ BEGIN EXECUTE format('CREATE SCHEMA %I', current_setting('search_path')); END $$;

CREATE TYPE user_status AS ENUM ('pending', 'email_verified', 'disabled', 'banned', 'deleting', 'deleted');

-- The columns of the real users table that the forum reads. BY DEFAULT, not ALWAYS: a test of the
-- app may insert the id its mocks sign in.
CREATE TABLE users (
    id         int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(255) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    -- Production defaults to pending; the forum's test users are confirmed accounts.
    status     user_status NOT NULL DEFAULT 'email_verified',
    deleted_at timestamptz
);
